export const formatUZS = (amount) =>
  `${new Intl.NumberFormat("uz-UZ").format(amount)} so'm`;

export function getDirectionsUrl(delivery, toDestination = false) {
  const destination = toDestination ? delivery.destination : delivery.storeAddress;
  const params = new URLSearchParams({
    api: "1",
    destination,
    travelmode: "driving",
  });
  if (toDestination) params.set("origin", delivery.storeAddress);
  return `https://www.google.com/maps/dir/?${params.toString()}`;
}
